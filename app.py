def update_subject_status(selected, completed, subjects):
    df = clean_subjects(subjects)

    if not selected:
        return (
            df,
            gr.update(choices=df["ชื่อวิชา"].tolist()),
            "กรุณาเลือกวิชาก่อน"
        )

    mask = df["ชื่อวิชา"] == selected

    if not mask.any():
        return (
            df,
            gr.update(choices=df["ชื่อวิชา"].tolist()),
            "ไม่พบวิชาที่เลือกในตาราง"
        )

    df.loc[mask, "สถานะ"] = (
        "เสร็จแล้ว" if completed else "ยังไม่เสร็จ"
    )

    return (
        df,
        gr.update(
            choices=df["ชื่อวิชา"].tolist(),
            value=selected
        ),
        f"บันทึกสถานะ *{selected}* แล้ว"
    )


