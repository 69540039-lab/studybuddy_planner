def create_plan(name, total_hours, start_time, subjects):
    try:
        df = clean_subjects(subjects)
        df = df[df["ชื่อวิชา"] != ""].copy()

        if df.empty:
            raise ValueError("กรุณากรอกชื่อวิชาอย่างน้อย 1 วิชา")

        hours = float(total_hours or 0)

        if hours <= 0:
            raise ValueError("เวลาว่างต้องมากกว่า 0 ชั่วโมง")

        start = datetime.strptime(
            str(start_time).strip(), "%H:%M"
        )

        analysis = analyze_subjects(df)
        analysis = analysis.sort_values(
            "คะแนนความสำคัญ", ascending=False
        ).reset_index(drop=True)

        total_minutes = int(hours * 60)
        study_budget = int(total_minutes * 0.9)
        break_budget = total_minutes - study_budget
        remaining = study_budget
        current = start
        plan_rows = []

        for _, row in analysis.iterrows():
            if remaining <= 0:
                break

            block = min(45, remaining)
            end_time = current + timedelta(minutes=block)

            plan_rows.append({
                "เวลา": (
                    f"{current.strftime('%H:%M')}–"
                    f"{end_time.strftime('%H:%M')}"
                ),
                "วิชา": row["วิชา"],
                "กิจกรรม": f"อ่าน/ทบทวน {row['ประเภท']}",
                "ระยะเวลา (นาที)": block,
                "คะแนนความสำคัญ": row["คะแนนความสำคัญ"],
                "คำแนะนำ": row["คำแนะนำ"]
            })

            current = end_time + timedelta(minutes=5)
            remaining -= block

        plan_df = pd.DataFrame(
            plan_rows,
            columns=[
                "เวลา", "วิชา", "กิจกรรม",
                "ระยะเวลา (นาที)",
                "คะแนนความสำคัญ", "คำแนะนำ"
            ]
        )

        done = int(
            df["สถานะ"].str.lower().isin(
                ["เสร็จแล้ว", "เสร็จ", "completed", "done"]
            ).sum()
        )

        overdue = analysis[
            analysis["ความเร่งด่วน"] == "เลยกำหนด"
        ]

        study_minutes = (
            int(plan_df["ระยะเวลา (นาที)"].sum())
            if not plan_df.empty else 0
        )

        summary = (
            "## 🗓️ สรุปแผนอ่านหนังสือ\n\n"
            f"- *ผู้ใช้:* {str(name).strip() or 'ไม่ระบุชื่อ'}\n"
            f"- *วันที่จัดแผน:* {TODAY.isoformat()}\n"
            f"- *จำนวนวิชา:* {len(df)} วิชา\n"
            f"- *วิชาที่เสร็จแล้ว:* {done} วิชา\n"
            f"- *จำนวนช่วงอ่าน:* {len(plan_df)} ช่วง\n"
            f"- *เวลาอ่านตามแผน:* {study_minutes} นาที\n"
            f"- *เวลาพักสำรองโดยประมาณ:* {break_budget} นาที\n\n"
            "ระบบจัดลำดับตามความยาก ความเข้าใจ และวันครบกำหนด "
            "โดยแบ่งช่วงอ่านไม่เกิน 45 นาที"
        )

        if not overdue.empty:
            summary += (
                "\n\n### ⚠️ วิชาที่เลยกำหนด\n\n"
                + ", ".join(overdue["วิชา"].astype(str).tolist())
                + "\n\nกรุณาตรวจสอบกำหนดสอบหรือวันส่งงาน"
            )

        if not plan_df.empty:
            time_chart = px.bar(
                plan_df,
                x="วิชา",
                y="ระยะเวลา (นาที)",
                color="กิจกรรม",
                title="เวลาอ่านหนังสือแยกตามวิชา"
            )
        else:
            time_chart = px.bar(title="ไม่มีตารางอ่านหนังสือ")

        if not analysis.empty:
            priority_chart = px.bar(
                analysis,
                x="วิชา",
                y="คะแนนความสำคัญ",
                color="ความเร่งด่วน",
                title="คะแนนความสำคัญรายวิชา"
            )
        else:
            priority_chart = px.bar(title="ไม่มีข้อมูลรายวิชา")

        excel = export_excel({
            "ตารางอ่าน": plan_df,
            "วิเคราะห์รายวิชา": analysis,
            "ข้อมูลวิชา": df
        })

        record_id = datetime.now().strftime("%Y%m%d%H%M%S%f")

        record = {
            "id": record_id,
            "created_at": datetime.now().strftime("%Y-%m-%d %H:%M"),
            "name": str(name).strip() or "ไม่ระบุชื่อ",
            "hours": hours,
            "start_time": str(start_time),
            "subjects": df.to_dict(orient="records"),
            "plan": plan_df.to_dict(orient="records"),
            "summary": summary
        }

        items = save_history(record)

        history_text = (
            "## 🕘 ประวัติแผนล่าสุด\n\n"
            + (
                "\n".join([
                    f"- {x.get('created_at', '')} — "
                    f"{x.get('name', '')} "
                    f"({len(x.get('subjects', []))} วิชา)"
                    for x in items[:10]
                ])
                if items else "ยังไม่มีประวัติ"
            )
        )

        progress = make_progress_html(done, len(df))

        dashboard_summary = (
            "## 📊 Dashboard\n\n"
            f"- จำนวนวิชา: **{len(df)}**\n"
            f"- เสร็จแล้ว: **{done}**\n"
            f"- ยังไม่เสร็จ: **{len(df) - done}**\n"
            f"- วิชาที่เลยกำหนด: *{len(overdue)}*"
        )

        choices = get_history_choices()

        return (
            summary, plan_df, excel,
            time_chart, priority_chart,
            dashboard_summary, analysis, progress,
            gr.update(
                choices=choices,
                value=choices[0] if choices else None
            ),
            history_text
        )

    except Exception as e:
        return (
            f"⚠️ สร้างแผนไม่สำเร็จ: {e}",
            pd.DataFrame(), None, None, None,
            "ยังไม่มีข้อมูล Dashboard",
            pd.DataFrame(columns=DASH_COLUMNS),
            make_progress_html(0, 0),
            gr.update(choices=get_history_choices(), value=None),
            "ไม่สามารถสร้างประวัติได้"
        )


