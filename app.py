# -------------------- วิเคราะห์รายวิชา --------------------

def analyze_subjects(df):
    rows = []

    for _, r in df.iterrows():
        if not r["ชื่อวิชา"]:
            continue

        due_raw = r["วันครบกำหนด (YYYY-MM-DD)"]

        try:
            due = date.fromisoformat(due_raw) if due_raw else None
            days_left = (due - TODAY).days if due else None
        except ValueError:
            due = None
            days_left = None

        if days_left is None:
            urgency = "ไม่ระบุวัน"
        elif days_left < 0:
            urgency = "เลยกำหนด"
        elif days_left <= 2:
            urgency = "เร่งด่วน"
        elif days_left <= 7:
            urgency = "ใกล้ถึงกำหนด"
        else:
            urgency = "ยังมีเวลา"

        priority = round(
            float(r["ความยาก (1-5)"]) * 2
            + (6 - float(r["ความเข้าใจ (1-5)"])) * 2
            + (
                4 if days_left is not None and days_left <= 2
                else 2 if days_left is not None and days_left <= 7
                else 0
            ),
            1
        )

        if float(r["ความเข้าใจ (1-5)"]) <= 2:
            recommendation = "ทบทวนซ้ำและทำโจทย์"
        elif float(r["ความยาก (1-5)"]) >= 4:
            recommendation = "ฝึกทำข้อสอบและสรุปประเด็น"
        else:
            recommendation = "ทบทวนตามกำหนด"

        if days_left is not None and days_left < 0:
            recommendation = "ตรวจสอบกำหนดส่งหรือสอบที่เลยกำหนด"

        rows.append({
            "วิชา": r["ชื่อวิชา"],
            "ประเภท": r["ประเภท (สอบ/ส่งงาน/อื่นๆ)"],
            "วันครบกำหนด": due_raw,
            "เหลือ (วัน)": (
                days_left if days_left is not None else "—"
            ),
            "ความเร่งด่วน": urgency,
            "คะแนนความสำคัญ": priority,
            "สถานะ": r["สถานะ"],
            "คำแนะนำ": recommendation
        })

    return pd.DataFrame(rows, columns=DASH_COLUMNS)


def export_excel(tables):
    path = tempfile.NamedTemporaryFile(
        suffix=".xlsx", delete=False
    ).name

    with pd.ExcelWriter(path, engine="openpyxl") as writer:
        for sheet, table in tables.items():
            if table is not None and not table.empty:
                table.to_excel(
                    writer,
                    sheet_name=sheet[:31],
                    index=False
                )

    return path


