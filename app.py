def create_weekly_plan(name, start_date, weekly_hours, subjects):
    try:
        df = clean_subjects(subjects)
        df = df[df["ชื่อวิชา"] != ""].copy()

        if df.empty:
            raise ValueError("กรุณากรอกข้อมูลรายวิชาก่อน")

        start = (
            date.fromisoformat(str(start_date))
            if start_date else TODAY
        )

        hours = float(weekly_hours or 0)

        if hours <= 0:
            raise ValueError(
                "เวลาว่างต่อสัปดาห์ต้องมากกว่า 0"
            )

        analysis = analyze_subjects(df).sort_values(
            "คะแนนความสำคัญ", ascending=False
        )

        total_minutes = int(hours * 60 * 0.9)
        minutes_per_day = max(1, total_minutes // 7)
        rows = []

        for day_num in range(7):
            day = start + timedelta(days=day_num)
            remaining = minutes_per_day
            idx = 0

            while remaining > 0 and idx < len(analysis):
                row = analysis.iloc[
                    (day_num + idx) % len(analysis)
                ]

                block = min(45, remaining)

                rows.append({
                    "วันที่": day.isoformat(),
                    "วัน": day.strftime("%A"),
                    "วิชา": row["วิชา"],
                    "กิจกรรม": f"อ่าน/ทบทวน {row['ประเภท']}",
                    "ระยะเวลา (นาที)": block,
                    "คะแนนความสำคัญ": row["คะแนนความสำคัญ"]
                })

                remaining -= block
                idx += 1

        weekly_df = pd.DataFrame(rows)

        summary = (
            "## 📅 แผนอ่านหนังสือ 7 วัน\n\n"
            f"- *ผู้ใช้:* {str(name).strip() or 'ไม่ระบุชื่อ'}\n"
            f"- *ช่วงวันที่:* {start.isoformat()} "
            f"ถึง {(start + timedelta(days=6)).isoformat()}\n"
            f"- *เวลาว่างต่อสัปดาห์:* {hours:g} ชั่วโมง\n"
            f"- *จำนวนช่วงอ่าน:* {len(weekly_df)} ช่วง\n"
            f"- *เวลาอ่านที่จัดตาราง:* "
            f"{int(weekly_df['ระยะเวลา (นาที)'].sum())} นาที\n\n"
            "แผนนี้เป็นแนวทางเบื้องต้น "
            "ควรปรับตามตารางเรียน งาน และเวลาพักจริง"
        )

        daily_totals = weekly_df.groupby(
            "วันที่", as_index=False
        )["ระยะเวลา (นาที)"].sum()

        chart = px.bar(
            daily_totals,
            x="วันที่",
            y="ระยะเวลา (นาที)",
            title="เวลาอ่านหนังสือรายวัน"
        )

        excel = export_excel({
            "แผน 7 วัน": weekly_df,
            "วิเคราะห์รายวิชา": analysis
        })

        return summary, weekly_df, chart, excel

    except Exception as e:
        return (
            f"⚠️ สร้างแผนรายสัปดาห์ไม่สำเร็จ: {e}",
            pd.DataFrame(), None, None
        )


