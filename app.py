def clean_subjects(data):
    if isinstance(data, pd.DataFrame):
        df = data.copy()
    elif data is None:
        df = DEFAULT_SUBJECTS.copy()
    else:
        df = pd.DataFrame(data, columns=SUBJECT_COLUMNS)

    for col in SUBJECT_COLUMNS:
        if col not in df.columns:
            df[col] = ""

    df = df[SUBJECT_COLUMNS].copy()
    df["ชื่อวิชา"] = (
        df["ชื่อวิชา"].fillna("").astype(str).str.strip()
    )
    df["ประเภท (สอบ/ส่งงาน/อื่นๆ)"] = (
        df["ประเภท (สอบ/ส่งงาน/อื่นๆ)"]
        .fillna("ทั่วไป").astype(str)
    )
    df["สถานะ"] = (
        df["สถานะ"].fillna("ยังไม่เสร็จ").astype(str)
    )

    for col in ["ความเข้าใจ (1-5)", "ความยาก (1-5)"]:
        df[col] = pd.to_numeric(
            df[col], errors="coerce"
        ).fillna(3).clip(1, 5)

    df["วันครบกำหนด (YYYY-MM-DD)"] = (
        df["วันครบกำหนด (YYYY-MM-DD)"]
        .fillna("").astype(str).str.strip()
    )

    return df


def read_history():
    if not os.path.exists(HISTORY_FILE):
        return []

    try:
        with open(HISTORY_FILE, "r", encoding="utf-8") as f:
            data = json.load(f)
        return data if isinstance(data, list) else []
    except Exception:
        return []


def write_history(items):
    with open(HISTORY_FILE, "w", encoding="utf-8") as f:
        json.dump(items, f, ensure_ascii=False, indent=2)


def save_history(record):
    items = read_history()
    items.insert(0, record)
    write_history(items[:50])
    return items


def get_history_choices():
    return [
        f"{x.get('created_at', '')} | "
        f"{x.get('name', 'ไม่ระบุชื่อ')} | "
        f"{x.get('id', '')}"
        for x in read_history()
    ]


def find_history(selection):
    if not selection:
        return None

    record_id = selection.rsplit("|", 1)[-1].strip()

    return next(
        (
            x for x in read_history()
            if str(x.get("id")) == record_id
        ),
        None
    )


